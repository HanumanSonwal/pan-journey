export const getCurrencySymbol = (currencyCode) => {
  try {
    const parts = new Intl.NumberFormat("en", {
      style: "currency",
      currency: currencyCode,
    }).formatToParts(1);

    return (
      parts.find((p) => p.type === "currency")?.value ||
      currencyCode
    );
  } catch {
    return currencyCode;
  }
};